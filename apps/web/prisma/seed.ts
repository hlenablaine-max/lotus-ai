async function main() {
  console.log('🌸 Iniciando seed dos agentes LOTUS...')

  for (const agent of AGENTS) {
    const result = await prisma.agent.upsert({
      where: { id: agent.id },
      update: {
        name: agent.name,
        title: agent.title,
        status: agent.status,
      },
      create: {
        ...agent,
        tools: [],
        permissions: [],
      },
    })
    console.log(`  ✓ ${result.name} (${result.department})`)
  }

  console.log(`\n✅ ${AGENTS.length} agentes sincronizados com sucesso!`)

  console.log('\n📦 Iniciando seed das soluções LOTUS...')

  for (const sol of SOLUTIONS) {
    const result = await prisma.solution.upsert({
      where: { id: sol.id },
      update: {
        name: sol.name,
        description: sol.description,
        baseSetupPrice: sol.baseSetupPrice,
        baseMonthlyPrice: sol.baseMonthlyPrice,
        isActive: true,
      },
      create: {
        ...sol,
        features: sol.features,
        components: sol.components,
        requiredDepartments: sol.requiredDepartments,
        isActive: true,
      },
    })
    console.log(`  ✓ ${result.name} (${result.category}) — R$${Number(result.baseSetupPrice).toLocaleString('pt-BR')} setup`)
  }

  console.log(`\n✅ ${SOLUTIONS.length} soluções sincronizadas com sucesso!`)
  console.log('\n🚀 Seed F1 completo!')
}

main()
  .catch((e) => {
    console.error('❌ Erro no seed:', e)
    process.exit(1)
  })
  .finally(async () => {
    await prisma.$disconnect()
  })
